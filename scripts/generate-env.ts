/**
 * Creates a development `.env` from `.env.example` with freshly generated
 * random secrets (JWT secrets, encryption key, dev account passwords).
 * Refuses to overwrite an existing .env unless --force is passed.
 *
 *   npm run setup:env
 */
import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(__dirname, '..');
const target = path.join(root, '.env');
const force = process.argv.includes('--force');

if (fs.existsSync(target) && !force) {
  console.log('.env already exists — leaving it unchanged (use --force to regenerate).');
  process.exit(0);
}

const secret = (bytes: number) => randomBytes(bytes).toString('base64url');
const password = () => `${randomBytes(6).toString('base64url')}-${randomBytes(4).toString('hex')}7`;

const devPassword = password();
const adminPassword = password();
const replacements: Record<string, string> = {
  JWT_ACCESS_SECRET: secret(48),
  JWT_REFRESH_SECRET: secret(48),
  ENCRYPTION_KEY: randomBytes(32).toString('base64'),
  DEV_USER_PASSWORD: devPassword,
  ADMIN_PASSWORD: adminPassword,
  TEST_FREE_PASSWORD: password(),
  TEST_PREMIUM_PASSWORD: password(),
  // Kokoon LMS integration: copy both into the LMS backend's env too (and nowhere else).
  LMS_SSO_SECRET: secret(48),
  LMS_API_SECRET: secret(48),
};

let text = fs.readFileSync(path.join(root, '.env.example'), 'utf8');
for (const [k, v] of Object.entries(replacements)) text = text.replace(new RegExp(`^${k}=.*$`, 'm'), `${k}=${v}`);
text = `# Generated by scripts/generate-env.ts on ${new Date().toISOString()} — DEVELOPMENT ONLY\n${text}`;
fs.writeFileSync(target, text, { mode: 0o600 });

console.log('Created .env with random development secrets.');
console.log('Development accounts (created by `npm run seed:dev`):');
console.log(`  student  ${process.env.DEV_USER_EMAIL ?? 'student@kokoon.local'}  /  ${devPassword}`);
console.log(`  admin    ${process.env.ADMIN_EMAIL ?? 'admin@kokoon.local'}  /  ${adminPassword}`);
console.log(`  free     ${process.env.TEST_FREE_EMAIL ?? 'free.tester@kokoon.local'}  /  ${replacements.TEST_FREE_PASSWORD}`);
console.log(`  premium  ${process.env.TEST_PREMIUM_EMAIL ?? 'premium.tester@kokoon.local'}  /  ${replacements.TEST_PREMIUM_PASSWORD}`);
console.log('These passwords are stored only in your local .env.');
console.log('LMS_SSO_SECRET and LMS_API_SECRET were generated too — copy them into the LMS backend env if you enable LMS_INTEGRATION_ENABLED.');
